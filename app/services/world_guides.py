def get_all_world_guides(query: Optional[str] = None, tag: Optional[str] = None) -> List[Dict[str, Any]]:
    """Return all world guides, with optional query or tag filtering."""
    guides = list(WORLD_GUIDES.values())
    if tag:
        tag_clean = tag.strip().lower()
        guides = [g for g in guides if any(tag_clean in t.lower() for t in g.get("tags", [])) or tag_clean in g.get("country", "").lower()]
    if query:
        q = query.strip().lower()
        guides = [
            g for g in guides
            if q in g.get("title", "").lower()
            or q in g.get("destination", "").lower()
            or q in g.get("city", "").lower()
            or q in g.get("country", "").lower()
            or q in g.get("excerpt", "").lower()
            or any(q in t.lower() for t in g.get("tags", []))
            or any(q in p.get("name", "").lower() for p in g.get("tourist_places", []))
        ]
    return guides


def get_world_guide_by_id(guide_id: str) -> Optional[Dict[str, Any]]:
    """Lookup a specific world guide by ID."""
    return WORLD_GUIDES.get(guide_id)


def clone_world_guide_to_trip(db: Session, guide_id: str, start_date: Optional[str] = None) -> Trip:
    """Instantiate a world travel guide into a real, fully editable Trip in the user's database."""
    guide = WORLD_GUIDES.get(guide_id)
    if not guide:
        raise ValueError(f"World guide with id '{guide_id}' not found.")

    try:
        s_date = datetime.strptime(start_date, "%Y-%m-%d").date() if start_date else (date.today() + timedelta(days=14))
    except Exception:
        s_date = date.today() + timedelta(days=14)

    trip_days = guide.get("recommended_days", 5)
    e_date = s_date + timedelta(days=trip_days - 1)

    new_trip = Trip(
        title=guide["title"],
        destination=guide["destination"],
        country=guide["country"],
        latitude=guide["latitude"],
        longitude=guide["longitude"],
        start_date=s_date.isoformat(),
        end_date=e_date.isoformat(),
        travel_style=guide.get("travel_style", "World Tour"),
        travel_pace=guide.get("travel_pace", "Moderate"),
        total_budget=guide.get("total_budget", 100000.0),
        currency=guide.get("currency", "INR"),
        cover_image=guide["cover_image"],
        notes=guide["description"]
    )
    db.add(new_trip)
    db.commit()
    db.refresh(new_trip)

    # 1. Add Itinerary Items
    order = 1
    for day_num, time_slot, title, loc_name, lat, lon, cost, category, notes in guide.get("itinerary_highlights", []):
        it_item = ItineraryItem(
            trip_id=new_trip.id,
            day_number=day_num,
            time_slot=time_slot,
            title=title,
            location=loc_name,
            description=notes,
            latitude=lat,
            longitude=lon,
            estimated_cost=cost,
            category=category,
            order_index=order
        )
        db.add(it_item)
        order += 1

    # 2. Add Transport Options
    for mode, title, route, fare, notes in guide.get("transports", []):
        t_opt = TransportOption(
            trip_id=new_trip.id,
            mode=mode,
            title=title,
            route=route,
            estimated_cost=fare,
            currency=new_trip.currency,
            booking_tips=notes
        )
        db.add(t_opt)

    # 3. Add Packing Items
    for p_desc in guide.get("packing_extras", []):
        p_item = PackingItem(
            trip_id=new_trip.id,
            category="Essentials",
            item_name=p_desc,
            is_packed=False,
            is_suggested=True
        )
        db.add(p_item)

    # 4. Add Initial Realistic Estimated Expenses
    b_total = guide.get("total_budget", 100000.0)
    exp_items = [
        ("Transit & Airfare / Rail Booking", round(b_total * 0.35, 2), "Transport", "Pre-booked transportation fares"),
        ("Accommodation Deposit", round(b_total * 0.35, 2), "Accommodation", "Hotel / stay advance deposit"),
        ("Activities & Sightseeing Passes", round(b_total * 0.18, 2), "Activities", "City tourist cards & museum tickets")
    ]
    for exp_title, exp_amt, exp_cat, exp_notes in exp_items:
        expense = Expense(
            trip_id=new_trip.id,
            title=exp_title,
            amount=exp_amt,
            category=exp_cat,
            date=new_trip.start_date,
            notes=exp_notes
        )
        db.add(expense)

    db.commit()
    db.refresh(new_trip)
    return new_trip
